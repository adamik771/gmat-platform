import { createHash } from "node:crypto"
import { existsSync, readdirSync, readFileSync, realpathSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, parse, resolve } from "node:path"
import process from "node:process"

const root = process.cwd()
const outputPath = join(root, "public", "third-party-notices.txt")
const checkOnly = process.argv.includes("--check")

function readJson(file) {
  return JSON.parse(readFileSync(file, "utf8"))
}

function packagePath(name) {
  return join(...name.split("/"))
}

function findPackageDir(name, fromDir) {
  let cursor = resolve(fromDir)
  const filesystemRoot = parse(cursor).root

  while (true) {
    const candidate = join(cursor, "node_modules", packagePath(name))
    if (existsSync(join(candidate, "package.json"))) return realpathSync(candidate)
    if (cursor === filesystemRoot) return null
    cursor = dirname(cursor)
  }
}

function normalizeLicense(value) {
  if (!value) return "Not declared"
  if (typeof value === "string") return value
  if (Array.isArray(value)) return value.map(normalizeLicense).join(", ")
  if (typeof value === "object" && typeof value.type === "string") return value.type
  return JSON.stringify(value)
}

function normalizeRepository(value) {
  if (!value) return "Not declared"
  const raw = typeof value === "string" ? value : value.url
  if (!raw) return "Not declared"
  return raw.replace(/^git\+/, "").replace(/\.git$/, "")
}

function normalizeNoticeText(value) {
  return value
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((line) => line.trimEnd())
    .join("\n")
    .trim()
}

function noticeFiles(packageDir) {
  return readdirSync(packageDir)
    .filter((name) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(name))
    .filter((name) => statSync(join(packageDir, name)).isFile())
    .sort((a, b) => a.localeCompare(b))
}

const rootPackage = readJson(join(root, "package.json"))
const queue = Object.keys(rootPackage.dependencies ?? {}).map((name) => ({
  name,
  fromDir: root,
}))
const packages = new Map()

while (queue.length > 0) {
  const request = queue.shift()
  const packageDir = findPackageDir(request.name, request.fromDir)
  if (!packageDir) {
    throw new Error(`Unable to resolve production dependency ${request.name} from ${request.fromDir}`)
  }

  const manifest = readJson(join(packageDir, "package.json"))
  const key = `${manifest.name}@${manifest.version}`
  if (packages.has(key)) continue

  const files = noticeFiles(packageDir).map((name) => ({
    name,
    text: normalizeNoticeText(readFileSync(join(packageDir, name), "utf8")),
  }))

  packages.set(key, {
    name: manifest.name,
    version: manifest.version,
    license: normalizeLicense(manifest.license ?? manifest.licenses),
    repository: normalizeRepository(manifest.repository),
    files,
  })

  const childNames = new Set([
    ...Object.keys(manifest.dependencies ?? {}),
    ...Object.keys(manifest.optionalDependencies ?? {}),
    ...Object.keys(manifest.peerDependencies ?? {}),
  ])

  for (const name of [...childNames].sort()) {
    const peerOptional = manifest.peerDependenciesMeta?.[name]?.optional === true
    if (peerOptional && !findPackageDir(name, packageDir)) continue
    if (findPackageDir(name, packageDir)) queue.push({ name, fromDir: packageDir })
  }
}

const lockDigest = createHash("sha256")
  .update(readFileSync(join(root, "package-lock.json")))
  .digest("hex")
const sortedPackages = [...packages.values()].sort((a, b) =>
  `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`),
)

const sections = sortedPackages.map((pkg) => {
  const fileText = pkg.files.length
    ? pkg.files
        .map(
          (file) =>
            `--- ${file.name} ---\n\n${file.text || "[File is empty]"}`,
        )
        .join("\n\n")
    : "No license or notice file was included in the installed package. The declared license above is reproduced from package.json; verify the upstream package before distribution."

  return [
    "=".repeat(80),
    `${pkg.name}@${pkg.version}`,
    `Declared license: ${pkg.license}`,
    `Repository: ${pkg.repository}`,
    "=".repeat(80),
    "",
    fileText,
  ].join("\n")
})

const output = [
  "ZAKARIAN GMAT THIRD-PARTY SOFTWARE NOTICES",
  "",
  "This file lists the installed production dependency graph and reproduces",
  "license and notice files distributed with those packages. Package authors",
  "retain all rights granted or reserved by their respective licenses.",
  "",
  "Generated by: npm run notices:generate",
  `package-lock.json SHA-256: ${lockDigest}`,
  `Packages recorded: ${sortedPackages.length}`,
  "",
  ...sections,
  "",
].join("\n")

if (checkOnly) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : ""
  if (current !== output) {
    console.error("Third-party notices are stale. Run npm run notices:generate.")
    process.exit(1)
  }
  console.log(`Third-party notices are current (${sortedPackages.length} packages).`)
} else {
  writeFileSync(outputPath, output)
  console.log(`Wrote ${outputPath} (${sortedPackages.length} packages).`)
}
